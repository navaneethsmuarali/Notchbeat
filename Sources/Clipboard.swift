// Clipboard history: remembers recent copies (stays on this Mac) and lets you copy them again.
import Cocoa
import SwiftUI

struct Clip: Identifiable, Codable, Equatable {
    enum Kind: String, Codable { case text, files, image }
    var id = UUID()
    var kind: Kind
    var text: String?
    var paths: [String]?
    var date = Date()

    var preview: String {
        switch kind {
        case .text: return (text ?? "").replacingOccurrences(of: "\n", with: " ").trimmingCharacters(in: .whitespaces)
        case .files:
            let names = (paths ?? []).map { ($0 as NSString).lastPathComponent }
            return names.count > 1 ? "\(names[0]) + \(names.count - 1) more" : (names.first ?? "")
        case .image: return "Image"
        }
    }
    var isLink: Bool { kind == .text && (text.map { $0.hasPrefix("http://") || $0.hasPrefix("https://") } ?? false) }
}

final class ClipboardHistory: ObservableObject {
    @Published private(set) var clips: [Clip] = []
    /// Images are only kept in memory, never written to disk.
    private(set) var images: [UUID: NSImage] = [:]
    @Published var enabled: Bool { didSet { UserDefaults.standard.set(enabled, forKey: "clipboardEnabled") } }

    private let maxClips = 60
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?
    private let file: URL = {
        let dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0].appendingPathComponent("Notchbeat")
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir.appendingPathComponent("clipboard.json")
    }()

    /// Pasteboard markers password managers and other apps use for things that shouldn't be recorded.
    private static let skipTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "com.typeit4me.clipping", "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type", "com.apple.is-remote-clipboard-transient",
    ]

    init() {
        enabled = UserDefaults.standard.object(forKey: "clipboardEnabled") as? Bool ?? true
        if let data = try? Data(contentsOf: file), let saved = try? JSONDecoder().decode([Clip].self, from: data) {
            clips = saved.filter { $0.kind != .image }
        }
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.check() }
    }

    private func save() {
        let keep = clips.filter { $0.kind != .image }
        if let data = try? JSONEncoder().encode(keep) { try? data.write(to: file, options: [.atomic]) }
    }

    private func check() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard enabled else { return }
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skipTypes) else { return }

        var clip: Clip?
        var image: NSImage?
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            clip = Clip(kind: .files, paths: urls.map(\.path))
        } else if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            clip = Clip(kind: .text, text: String(s.prefix(20_000)))
        } else if let img = NSImage(pasteboard: pb) {
            clip = Clip(kind: .image)
            image = img
        }
        guard var c = clip else { return }

        // Same content copied again: move it to the top instead of duplicating.
        if let i = clips.firstIndex(where: { $0.kind == c.kind && $0.kind != .image && $0.text == c.text && $0.paths == c.paths }) {
            c = clips.remove(at: i)
            c.date = Date()
        }
        clips.insert(c, at: 0)
        if let image { images[c.id] = image }
        if clips.count > maxClips {
            clips.suffix(from: maxClips).forEach { images[$0.id] = nil }
            clips.removeLast(clips.count - maxClips)
        }
        save()
    }

    func copy(_ c: Clip) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch c.kind {
        case .text: pb.setString(c.text ?? "", forType: .string)
        case .files: pb.writeObjects((c.paths ?? []).map { URL(fileURLWithPath: $0) as NSURL })
        case .image: if let img = images[c.id] { pb.writeObjects([img]) }
        }
        lastChange = pb.changeCount
        if let i = clips.firstIndex(of: c) {
            var moved = clips.remove(at: i)
            moved.date = Date()
            clips.insert(moved, at: 0)
            save()
        }
    }

    func delete(_ c: Clip) { clips.removeAll { $0.id == c.id }; images[c.id] = nil; save() }
    func clear() { clips.removeAll(); images.removeAll(); save() }
}

struct ClipboardView: View {
    @ObservedObject var c: ClipboardHistory
    var onPaste: ((Clip) -> Void)? = nil
    var onClose: (() -> Void)? = nil
    @State private var copied: UUID?
    @State private var selection = 0
    @FocusState private var focused: Bool

    var body: some View {
        VStack(alignment: .leading, spacing: 4) {
            HStack {
                Text(c.enabled ? "Click to copy · ↑↓ + Return to paste · 1–9" : "Clipboard history is paused")
                    .font(.system(size: 10, weight: .medium)).foregroundStyle(.white.opacity(0.5))
                Spacer()
                if !c.clips.isEmpty {
                    Button("Clear") { c.clear() }
                        .buttonStyle(.plain).font(.system(size: 10, weight: .semibold)).foregroundStyle(.white.opacity(0.7))
                }
            }
            if c.clips.isEmpty {
                Text("Things you copy will show up here.")
                    .font(.system(size: 12)).foregroundStyle(.white.opacity(0.5))
                    .frame(maxWidth: .infinity, maxHeight: .infinity)
            } else {
                ScrollViewReader { proxy in
                    ScrollView(.vertical, showsIndicators: false) {
                        LazyVStack(spacing: 2) {
                            ForEach(Array(c.clips.enumerated()), id: \.element.id) { i, clip in
                                row(clip, index: i).id(clip.id)
                            }
                        }
                    }
                    .onChange(of: selection) { _, new in
                        if c.clips.indices.contains(new) { withAnimation(.easeOut(duration: 0.12)) { proxy.scrollTo(c.clips[new].id) } }
                    }
                }
            }
        }
        .focusable()
        .focusEffectDisabled()
        .focused($focused)
        .onAppear { selection = 0; DispatchQueue.main.async { focused = true } }
        .onKeyPress(.downArrow) { selection = min(selection + 1, max(0, c.clips.count - 1)); return .handled }
        .onKeyPress(.upArrow) { selection = max(selection - 1, 0); return .handled }
        .onKeyPress(.return) {
            if c.clips.indices.contains(selection) { onPaste?(c.clips[selection]) }
            return .handled
        }
        .onKeyPress(.escape) { onClose?(); return .handled }
        .onKeyPress(characters: .decimalDigits) { press in
            if let n = Int(press.characters), n >= 1, n <= c.clips.count { onPaste?(c.clips[n - 1]) }
            return .handled
        }
    }

    private func row(_ clip: Clip, index: Int) -> some View {
        Button {
            c.copy(clip)
            copied = clip.id
            DispatchQueue.main.asyncAfter(deadline: .now() + 1) { if copied == clip.id { copied = nil } }
        } label: {
            HStack(spacing: 8) {
                icon(clip).frame(width: 22, height: 22)
                Text(clip.preview).font(.system(size: 12)).foregroundStyle(.white.opacity(0.9)).lineLimit(1)
                Spacer(minLength: 6)
                if copied == clip.id {
                    Text("Copied").font(.system(size: 10, weight: .semibold)).foregroundStyle(.green)
                } else {
                    Text(ago(clip.date)).font(.system(size: 10)).foregroundStyle(.white.opacity(0.4))
                }
            }
            .padding(.horizontal, 6)
            .frame(height: 28)
            .background(RoundedRectangle(cornerRadius: 8).fill(Color.white.opacity(focused && index == selection ? 0.14 : 0)))
            .overlay(alignment: .leading) {
                if index < 9 && focused {
                    Text("\(index + 1)").font(.system(size: 9, weight: .bold)).foregroundStyle(.white.opacity(0.35)).offset(x: -10)
                }
            }
            .contentShape(Rectangle())
        }
        .buttonStyle(RowStyle())
        .contextMenu {
            Button("Copy") { c.copy(clip) }
            if clip.isLink, let s = clip.text, let u = URL(string: s.trimmingCharacters(in: .whitespacesAndNewlines)) {
                Button("Open Link") { NSWorkspace.shared.open(u) }
            }
            Divider()
            Button("Delete") { c.delete(clip) }
        }
    }

    @ViewBuilder private func icon(_ clip: Clip) -> some View {
        switch clip.kind {
        case .image:
            if let img = c.images[clip.id] {
                Image(nsImage: img).resizable().aspectRatio(contentMode: .fill).frame(width: 22, height: 22).clipShape(RoundedRectangle(cornerRadius: 4))
            } else { Image(systemName: "photo").foregroundStyle(.white.opacity(0.6)) }
        case .files:
            if let p = clip.paths?.first {
                Image(nsImage: NSWorkspace.shared.icon(forFile: p)).resizable().frame(width: 20, height: 20)
            }
        case .text:
            Image(systemName: clip.isLink ? "link" : "text.alignleft").font(.system(size: 11)).foregroundStyle(.white.opacity(0.6))
        }
    }

    private func ago(_ d: Date) -> String {
        let s = Int(Date().timeIntervalSince(d))
        if s < 60 { return "now" }
        if s < 3600 { return "\(s / 60)m" }
        if s < 86400 { return "\(s / 3600)h" }
        return "\(s / 86400)d"
    }
}
